"""Deterministic namespace facade over GramFlux's generated official definitions."""

from .model import Definition, class_name, python_name


def generate_namespaces(definitions: tuple[Definition, ...], layer: int) -> str:
    groups: dict[str, dict[str, list[tuple[str, str]]]] = {"types": {}, "functions": {}}
    results = set()
    for definition in definitions:
        if definition.name == "vector":
            continue
        parts = definition.name.split(".")
        namespace = parts[0] if len(parts) > 1 else ""
        name = python_name(
            parts[-1][:1].upper() + parts[-1][1:] + ("Request" if definition.method else "")
        )
        kind = "functions" if definition.method else "types"
        groups[kind].setdefault(namespace, []).append((name, class_name(definition)))
        if not definition.method and definition.result.isidentifier():
            results.add(definition.result)
    lines = [
        "# Generated by gramflux.tools.schema; do not edit.",
        '"""Native API namespaces from the pinned official TL schema."""',
        "from typing import Any, TypeAlias",
        "from .tl.generated import objects as _objects",
        f"LAYER = {layer}",
        "",
    ]
    for kind, namespaces in groups.items():
        for namespace, values in sorted(namespaces.items()):
            label = f"_{kind}_{namespace or 'root'}"
            lines.append(f"class {label}:")
            for name, original in sorted(values):
                lines.append(f"    {name}: TypeAlias = _objects.{original}")
            if kind == "types" and not namespace:
                for result in sorted(results):
                    if result not in ("Object", "Bool", "true"):
                        lines.append(f"    Type{result}: TypeAlias = Any")
            lines.append("")
        lines.append(f"class _{kind}(_{kind}_root):")
        for namespace in sorted(namespaces):
            if namespace:
                lines.append(f"    {namespace}: TypeAlias = _{kind}_{namespace}")
        lines.append(f"{kind} = _{kind}\n")
    return "\n".join(lines)
