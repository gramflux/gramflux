"""Deterministic asynchronous facade over every pinned official API function."""

import re

from .generator import annotation
from .model import Definition, class_name, python_name


def method_name(name: str) -> str:
    """Convert an official camelCase method name into a Python identifier."""
    first = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    return python_name(re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", first).lower())


def generate_methods(definitions: tuple[Definition, ...], digest: str, layer: int) -> str:
    groups: dict[str, list[Definition]] = {"": []}
    results: dict[str, list[str]] = {}
    for definition in definitions:
        if definition.method:
            namespace = definition.name.rpartition(".")[0]
            groups.setdefault(namespace, []).append(definition)
        elif definition.name != "vector":
            results.setdefault(definition.result, []).append("objects." + class_name(definition))

    def returns(kind: str) -> str:
        if kind.startswith(("Vector<", "vector<")):
            return f"list[{returns(kind[kind.index('<') + 1 : -1])}]"
        primitive = annotation(kind)
        if primitive != "TLObject":
            return primitive
        return " | ".join(results.get(kind, ["TLObject"]))

    lines = [
        "# Generated by python -m gramflux.tools.schema generate; DO NOT EDIT.",
        f"# Source SHA256: {digest}; API layer: {layer}",
        "from __future__ import annotations",
        "import builtins",
        "from typing import Any, Protocol, cast",
        "from gramflux.tl.model import TLObject",
        "from gramflux.tl.generated import objects",
        "",
        "class Invoker(Protocol):",
        "    async def invoke(self, request: TLObject) -> Any: ...",
        "",
    ]
    for namespace, methods in sorted(groups.items(), key=lambda item: (not bool(item[0]), item[0])):
        cls = "API" + namespace.title().replace(".", "")
        lines += [
            f"class {cls}:",
            f'    """Official {namespace or "root"} functions from the pinned TL schema."""',
            "    __slots__ = ('_client',"
            + ("".join(f" '{n}'," for n in sorted(groups) if n) if not namespace else "")
            + ")",
            "",
            "    def __init__(self, client: Invoker) -> None:",
            "        self._client = client",
        ]
        if not namespace:
            lines += [
                f"        self.{n} = API{n.title().replace('.', '')}(client)"
                for n in sorted(groups)
                if n
            ]
        seen: set[str] = set(groups if not namespace else ())
        seen.add("_client")
        for definition in sorted(methods, key=lambda d: d.name):
            name = method_name(definition.name.rsplit(".", 1)[-1])
            if name in seen:
                raise ValueError(f"async API name collision: {namespace}.{name}")
            seen.add(name)
            params = [p for p in definition.params if p.type != "#"]
            signature = []
            for parameter in params:
                default = (
                    " = False"
                    if parameter.type.endswith("?true")
                    else " = None"
                    if "?" in parameter.type
                    else ""
                )
                base = parameter.type.split("?", 1)[-1]
                hint = returns(base)
                if "?" in parameter.type and base != "true":
                    hint += " | None"
                signature.append(f"{python_name(parameter.name)}: {hint}{default}")
            forwarded = []
            for parameter in params:
                name_arg = python_name(parameter.name)
                # Dataclass vector fields use list[TLObject]; list is invariant.
                # The exact input constructor union is narrower and codec-read-only.
                # Cast only at this generated boundary without copying user buffers.
                legacy = annotation(parameter.type).replace("list[", "builtins.list[")
                value = (
                    f"cast('{legacy}', {name_arg})"
                    if "list[" in legacy and "TLObject" in legacy
                    else name_arg
                )
                forwarded.append(f"{name_arg}={value}")
            args = ", ".join(forwarded)
            result = returns(definition.result)
            lines += [
                "",
                f"    async def {name}(self"
                + (", *, " + ", ".join(signature) if params else "")
                + f") -> {result}:",
                f'        """Invoke {definition.name} (#{definition.id:08x})."""',
                f"        return cast('{result}', "
                f"await self._client.invoke(objects.{class_name(definition)}({args})))",
            ]
        lines.append("")
    return "\n".join(lines)
