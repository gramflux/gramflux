"""Deterministic typed dataclass generator. No network access."""

from .model import Definition, class_name, python_name


def annotation(t: str) -> str:
    optional = "?" in t
    t = t.split("?", 1)[-1]
    if t.startswith(("Vector<", "vector<")):
        value = f"list[{annotation(t[t.index('<') + 1 : -1])}]"
    else:
        value = {
            "int": "int",
            "long": "int",
            "#": "int",
            "int128": "bytes",
            "int256": "bytes",
            "double": "float",
            "string": "str",
            "bytes": "bytes",
            "Bool": "bool",
            "true": "bool",
        }.get(t, "TLObject")
    return value + (" | None" if optional and t != "true" else "")


def generate(definitions: tuple[Definition, ...], digest: str) -> str:
    lines = [
        "# Generated by python -m gramflux.tools.schema generate; DO NOT EDIT.",
        f"# Source SHA256: {digest}",
        "from __future__ import annotations",
        "from dataclasses import dataclass",
        "from typing import ClassVar",
        "from gramflux.tl.model import Definition, Parameter, TLObject",
        "",
    ]
    names: set[str] = set()
    for d in definitions:
        name = class_name(d)
        if name in names:
            raise ValueError(f"Python class collision: {name}")
        names.add(name)
        lines += [
            "@dataclass(slots=True, kw_only=True, repr=False)",
            f"class {name}(TLObject):",
            f"    definition: ClassVar[Definition] = {d!r}",
        ]
        for p in d.params:
            # Flags are calculated, never part of the generated public constructor.
            if p.type == "#":
                continue
            default = " = False" if p.type.endswith("?true") else " = None" if "?" in p.type else ""
            lines.append(f"    {python_name(p.name)}: {annotation(p.type)}{default}")
        lines.append("")
    lines += ["REGISTRY: dict[int, type[TLObject]] = {"]
    lines += [f"    {d.id}: {class_name(d)}," for d in definitions]
    lines += ["}", ""]
    return "\n".join(lines)
