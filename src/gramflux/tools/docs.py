"""Generate deterministic English reference pages from the installed Python API.

No credentials or network access are used. Run from a repository checkout.
"""

import argparse
import inspect
import json
from dataclasses import fields, is_dataclass
from pathlib import Path
from typing import Any, get_args

from gramflux import Client, Config, Session, __version__, buttons, events, filters
from gramflux import errors as errors_module
from gramflux.tl.generated.objects import REGISTRY
from gramflux.tl.methods import method_name
from gramflux.tl.model import class_name, python_name

GENERATED = "<!-- Generated by python -m gramflux.tools.docs; do not edit by hand. -->"


def page(title: str, description: str) -> list[str]:
    return [
        "---",
        f"title: {json.dumps(title)}",
        f"description: {json.dumps(description)}",
        "---",
        "",
        GENERATED,
        "",
        f"# {title}",
        "",
    ]


def type_name(value: Any) -> str:
    if value is inspect.Signature.empty:
        return "Any"
    if isinstance(value, str):
        return value.strip("'\"")
    if value is None or value is type(None):
        return "None"
    if isinstance(value, type):
        return value.__name__
    text = str(value).replace("typing.", "").replace("gramflux.tl.generated.objects.", "")
    return text.replace("gramflux.", "")


def table_type(value: Any) -> str:
    """Escape union bars so GFM tables retain a single type cell."""
    return type_name(value).replace("|", r"\|")


def signature(name: str, value: Any) -> str:
    sig = inspect.signature(value)
    parameters = []
    keyword_only = False
    for parameter in sig.parameters.values():
        if parameter.name in {"self", "cls"} or parameter.name.startswith("_"):
            continue
        if parameter.kind == parameter.KEYWORD_ONLY and not keyword_only:
            parameters.append("*")
            keyword_only = True
        prefix = (
            "*"
            if parameter.kind == parameter.VAR_POSITIONAL
            else "**"
            if parameter.kind == parameter.VAR_KEYWORD
            else ""
        )
        if prefix == "*":
            keyword_only = True
        text = prefix + parameter.name
        if parameter.annotation is not parameter.empty:
            text += ": " + type_name(parameter.annotation)
        if parameter.default is not parameter.empty:
            default = parameter.default
            rendered = (
                "filters.all_messages" if isinstance(default, filters.Filter) else repr(default)
            )
            if " at 0x" in rendered:
                raise ValueError(f"unstable default representation for {name}.{parameter.name}")
            text += " = " + rendered
        parameters.append(text)
    prefix = (
        "async " if inspect.iscoroutinefunction(value) or inspect.isasyncgenfunction(value) else ""
    )
    return f"{prefix}def {name}({', '.join(parameters)}) -> {type_name(sig.return_annotation)}"


def render() -> dict[str, str]:
    output: dict[str, str] = {}
    lines = page(
        "Client", "Complete public Client signatures generated from the Python implementation."
    )
    lines += [
        f"Reference for GramFlux **{__version__}**. Generated from the actual public API.",
        "",
        "Constructing a Client does not connect or authorize it. Use an async context",
        "manager; register handlers before entering.",
        "[Start here](../getting-started/quickstart.md).",
        "",
        "```python",
        signature("Client", Client),
        "```",
        "",
        "## Properties",
        "",
        "| Property | Meaning |",
        "| --- | --- |",
        "| `connected` | Native connection state; does not imply authorization. |",
        "| `api` | Cached typed raw API facade; see [all raw methods](raw/index.md). |",
        "| `login_stage` | Saved `code`, `password` or None; available after connect. |",
        "| `login_challenge` | Saved LoginChallenge for explicit sign_in, or None. |",
        "",
        "## Methods",
        "",
    ]
    methods = [
        (n, v) for n, v in inspect.getmembers(Client, inspect.isfunction) if not n.startswith("_")
    ]
    lines += [
        f"{len(methods)} public methods, including lifecycle, subscriptions and stream factories.",
        "This is not a count of Telegram RPC endpoints.",
        "",
    ]
    for name, value in methods:
        lines += [f"### {name}", "", "```python", signature(name, value), "```", ""]
        doc = inspect.getdoc(value)
        if doc:
            lines += [doc, ""]
    output["client.md"] = "\n".join(lines)

    lines = page(
        "Sessions and configuration", "Session factories and immutable Config field defaults."
    )
    for cls in (Session, Config):
        lines += [f"## {cls.__name__}", "", inspect.getdoc(cls) or "", ""]
        for name, method_value in inspect.getmembers(cls, inspect.ismethod):
            if not name.startswith("_"):
                lines += [
                    f"### {cls.__name__}.{name}",
                    "",
                    "```python",
                    signature(name, method_value),
                    "```",
                    "",
                ]
        if cls is Config:
            lines += ["| Field | Type | Default |", "| --- | --- | --- |"]
            lines += [
                f"| `{f.name}` | `{table_type(f.type)}` | `{f.default!r}` |" for f in fields(cls)
            ]
    lines += [
        "",
        "See [configuration behavior](../guides/configuration.md)",
        "and [session security](../guides/sessions.md).",
        "",
    ]
    output["configuration.md"] = "\n".join(lines)

    lines = page("Events", "Fields, properties and helpers of all high-level event classes.")
    lines += [
        "Callbacks execute sequentially through the bounded dispatcher.",
        "See [ordering and failure behavior](../guides/events.md). Raw Update constructors",
        "are listed separately from these high-level event classes.",
        "",
    ]
    for cls in get_args(events.Event):
        lines += [f"## {cls.__name__}", "", "| Field | Type |", "| --- | --- |"]
        if is_dataclass(cls):
            lines += [f"| `{f.name}` | `{table_type(f.type)}` |" for f in fields(cls)]
        lines += [""]
        for name, value in inspect.getmembers(cls):
            if isinstance(value, property) and value.fget is not None:
                lines += [
                    f"- `{name}`: `{type_name(inspect.signature(value.fget).return_annotation)}`"
                ]
            elif inspect.isfunction(value) and not name.startswith("_"):
                lines += ["", "```python", signature(name, value), "```", ""]
        lines += [""]
    output["events.md"] = "\n".join(lines)

    for module, title in ((filters, "Filters"), (buttons, "Buttons and inline results")):
        lines = page(title, f"Public {title.lower()} exported by GramFlux.")
        for name, value in inspect.getmembers(module):
            if name.startswith("_"):
                continue
            if isinstance(value, filters.Filter):
                lines += [
                    f"## {name}",
                    "",
                    f"`filters.{name}` is a composable synchronous predicate.",
                    "",
                ]
            elif inspect.isfunction(value) and value.__module__ == module.__name__:
                lines += [
                    f"## {name}",
                    "",
                    "```python",
                    signature(name, value),
                    "```",
                    "",
                    inspect.getdoc(value) or "",
                    "",
                ]
        output["filters.md" if module is filters else "buttons.md"] = "\n".join(lines)

    lines = page("Errors", "Native GramFlux exception classes and their inheritance.")
    lines += [
        "See [handling errors](../guides/errors.md) for retry and ambiguous-outcome policies.",
        "",
    ]
    for name, error_cls in inspect.getmembers(errors_module, inspect.isclass):
        if error_cls.__module__ != errors_module.__name__:
            continue
        lines += [
            f"## {name}",
            "",
            f"**Base:** `{error_cls.__bases__[0].__name__}`",
            "",
            inspect.getdoc(error_cls) or "No additional contract beyond the base class.",
            "",
        ]
    output["errors.md"] = "\n".join(lines)

    groups: dict[str, list[Any]] = {}
    for raw_cls in REGISTRY.values():
        if raw_cls.definition.method:
            groups.setdefault(raw_cls.definition.name.rpartition(".")[0] or "root", []).append(
                raw_cls
            )
    lines = page(
        "Raw Telegram API", "Every pinned official Telegram function, grouped by namespace."
    )
    lines += [
        "All **783 functions** in the pinned official layer **225** are exposed as typed",
        "async methods under `client.api`. They use the independent native engine.",
        "",
        "Generated coverage does not certify authenticated end-to-end usability. Server",
        "permissions, method-specific workflows and",
        "[runtime limitations](../../design/compatibility.md)",
        "still apply. Required hashes, IDs and peer objects are the caller's responsibility.",
        "",
        "Read [raw API usage](../../guides/async-api.md) before using this reference.",
        "",
        "| Namespace | Methods |",
        "| --- | --- |",
    ]
    for namespace, declarations in sorted(groups.items()):
        lines.append(f"| [{namespace}]({namespace}.md) | {len(declarations)} |")
        section = page(
            f"Raw API: {namespace}",
            f"Official {namespace} functions, parameter types and native request bindings.",
        )
        section += [
            "Types below are **official TL types**, not Python import paths. TL sum types",
            "decode to their native constructor classes; primitives and vectors become",
            "Python scalars and lists. Optional fields use None; flag-only booleans use False.",
            "No implicit peer resolution or application-request retries are added.",
            "",
        ]
        for declaration_cls in sorted(declarations, key=lambda item: item.definition.name):
            d = declaration_cls.definition
            method = method_name(d.name.rsplit(".", 1)[-1])
            path = "client.api." + (namespace + "." if namespace != "root" else "") + method
            section += [
                f"## {method}",
                "",
                f"**Call:** `{path}(...)`",
                "",
                f"**Official method:** `{d.name}` · **ID:** `0x{d.id:08x}`",
                "",
                f"**Result:** `{d.result}`",
                "",
                f"**Request class:** `gramflux.tl.generated.objects.{class_name(d)}`",
                "",
            ]
            params = [p for p in d.params if p.type != "#"]
            if params:
                section += ["| Keyword | TL type | Required / default |", "| --- | --- | --- |"]
                for parameter in params:
                    default = (
                        "False"
                        if parameter.type.endswith("?true")
                        else "None"
                        if "?" in parameter.type
                        else "Required"
                    )
                    section.append(
                        f"| `{python_name(parameter.name)}` | `{parameter.type}` | {default} |"
                    )
                section += [""]
            else:
                section += ["No parameters.", ""]
            section += [
                f"[Official Telegram method documentation](https://core.telegram.org/method/{d.name})",
                "",
            ]
        output[f"raw/{namespace}.md"] = "\n".join(section)
    lines += ["", "[Exact machine-readable API inventory](../../api-surface.json).", ""]
    output["raw/index.md"] = "\n".join(lines)
    from .docs_reference import expand

    return expand(output)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated pages differ")
    parser.add_argument("--output", type=Path, default=Path("docs/reference"))
    args = parser.parse_args()
    expected = render()
    existing = {str(p.relative_to(args.output)): p for p in args.output.rglob("*.md")}
    if args.check:
        changed = [
            name
            for name, text in expected.items()
            if name not in existing or existing[name].read_text() != text
        ]
        if changed or existing.keys() - expected.keys():
            raise SystemExit("Reference differs; run python -m gramflux.tools.docs")
        print(f"Verified {len(expected)} reference pages; 783 official async functions")
        return
    for name in existing.keys() - expected.keys():
        if GENERATED not in existing[name].read_text():
            raise SystemExit(f"refusing to remove handwritten reference: {name}")
        existing[name].unlink()
    for name, text in expected.items():
        path = args.output / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and GENERATED not in path.read_text():
            raise SystemExit(f"refusing to overwrite handwritten reference: {name}")
        path.write_text(text)
    print(f"Generated {len(expected)} reference pages")


if __name__ == "__main__":
    main()
