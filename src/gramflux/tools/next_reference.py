"""Generate the Next-Generation API reference from real signatures and delegation data."""

import argparse
import inspect
import json
from pathlib import Path

from gramflux import resources, routing
from gramflux._raw_view import Raw
from gramflux.tools.docs import signature
from gramflux.tools.docs_reference import load_content, parameter_table

OUTPUT = Path("docs/next-api/reference.md")
DATA = Path(__file__).with_name("data") / "next_api_mapping.json"


def render() -> str:
    content = load_content()
    mapping = json.loads(DATA.read_text())
    lines = [
        "---",
        "title: Next-Generation API reference",
        "description: Signatures, parameters and delegation for every new domain and resource.",
        "---",
        "",
        "<!-- Generated by python -m gramflux.tools.next_reference; do not edit. -->",
        "",
        "# Next-Generation API reference",
        "",
        "All views are local, lazy objects sharing one Client. They do not authenticate,",
        "resolve peers, open files or make requests merely because you access a domain",
        "or construct a chat resource. Operations delegate to the linked legacy contract.",
        "",
        "## Client views",
        "",
        "| Entry point | View | Purpose |",
        "| --- | --- | --- |",
    ]
    views = {
        "auth": "Auth",
        "account": "Account",
        "peers": "Peers",
        "files": "Files",
        "contacts": "Contacts",
        "dialogs": "Dialogs",
        "bot": "Bot",
        "invites": "Invites",
        "membership": "Membership",
        "chat(peer)": "ChatResource",
    }
    for path, cls in views.items():
        lines.append(f"| `client.{path}` | `{cls}` | {inspect.getdoc(getattr(resources, cls))} |")
    lines += [
        "| `client.events` | `EventManager` | Mount/unmount routers on the existing dispatcher |",
        "| `client.raw` | `Raw` | Existing typed namespaces plus invoke; no alternate engine |",
        "",
        "`client.chat` is a cached callable ChatFactory. Each call returns a new local",
        "ChatResource retaining the original peer reference. Access history, search or",
        "members for their separate list and iterator methods. No resolved-peer cache is added.",
        "",
    ]
    for cls_name, methods in mapping.items():
        cls = getattr(resources, cls_name)
        prefix = next(
            ("client." + k for k, v in views.items() if v == cls_name),
            {"History": "chat.history", "Search": "chat.search", "Members": "chat.members"}.get(
                cls_name, cls_name
            ),
        )
        if cls_name == "ChatResource":
            prefix = "chat"
        lines += [f"## {cls_name}", "", inspect.getdoc(cls) or "", ""]
        for name, legacy in methods.items():
            fn = getattr(cls, name)
            lines += [
                f"### {prefix}.{name}",
                "",
                "```python",
                signature(name, fn),
                "```",
                "",
                content["methods"][legacy]["summary"],
                "",
                f"Delegates to [Client.{legacy}](../reference/client/{legacy}.md).",
                "",
            ]
            parameters = parameter_table(legacy, fn, content)
            lines += [
                (
                    "#### " + line[3:]
                    if line.startswith("## ")
                    else "##### " + line[4:]
                    if line.startswith("### ")
                    else line
                )
                for line in parameters
            ]
            lines += [
                "**Returns:** " + content["methods"][legacy]["returns"],
                "",
                "**Errors and execution:** identical to the linked Client operation. "
                "Iterator factories retain lazy execution and failure timing; other async "
                "operations execute when awaited. No retries or permission preflight are added.",
                "",
            ]
    lines += [
        "## Router and event management",
        "",
        "[Routing contracts and examples](routing.md) · [Command parsing](commands.md)",
        "",
    ]
    for routing_cls in (
        routing.Router,
        routing.EventManager,
        routing.Subscription,
        routing.CommandContext,
    ):
        lines += [f"### {routing_cls.__name__}", "", inspect.getdoc(routing_cls) or "", ""]
        for name, fn in inspect.getmembers(routing_cls, inspect.isfunction):
            if name.startswith("_"):
                continue
            lines += ["```python", signature(name, fn), "```", "", inspect.getdoc(fn) or "", ""]
    lines += [
        "## Raw API",
        "",
        "```python",
        signature("invoke", Raw.invoke),
        "```",
        "",
        "`client.raw` inherits the existing typed facade; every namespace and generated",
        "signature remains the same as [client.api](../reference/raw/index.md).",
        "No generated TL declaration was changed for this layer.",
        "",
        "## Additional properties",
        "",
        "`client.auth.stage` and `.challenge` delegate to Client.login_stage and",
        "Client.login_challenge. Reading the challenge can create a new immutable value;",
        "use value equality rather than object identity. `Subscription.active` is read-only.",
        "",
        "`CommandContext` exposes event, message, command, args, raw_args and client;",
        "its reply helper delegates to the original MessageEvent. See the command guide",
        "for exact whitespace, direction, prefix, username and case rules.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            raise SystemExit(
                "Next API reference differs; run python -m gramflux.tools.next_reference"
            )
        print("Next-Generation API reference matches actual signatures")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text)
        print("Generated Next-Generation API reference")


if __name__ == "__main__":
    main()
