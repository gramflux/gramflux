const fs = require('node:fs');
const path = require('node:path');
const content = require('../src/gramflux/tools/data/client_reference.json');
const clientGroups = {};
for (const [name, info] of Object.entries(content.methods)) {
  const slug = name === '__init__' ? 'constructor' : name;
  (clientGroups[info.category] ??= []).push(`reference/client/${slug}`);
}
const clientSections = Object.entries(clientGroups).map(([label, items]) => ({
  type: 'category', label, items: items.sort(),
}));
const rawSections = fs.readdirSync(path.join(__dirname, '../docs/reference/raw'), {withFileTypes: true})
  .filter(entry => entry.isDirectory())
  .map(entry => ({type: 'category', label: entry.name,
    link: {type: 'doc', id: `reference/raw/${entry.name}`},
    items: [{type: 'autogenerated', dirName: `reference/raw/${entry.name}`}]}));

